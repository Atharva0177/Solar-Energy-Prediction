"""Build the model-comparison artifacts (PRD §26) from per-model metrics.

Reads ``artifacts/{baselines,xgboost,lstm,gru,transformer}/metrics*.csv`` and
writes:

* ``artifacts/evaluation/model_comparison.csv``  — ALL-sites rows, every model
* ``artifacts/evaluation/model_comparison.json`` — same + per-site spread
* ``artifacts/evaluation/evaluation_report.md``  — ranked table + notes

All numbers are copied verbatim from the source metric files (PRD Rule 4: no
fabrication); models without artifacts yet are skipped with a note.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
METRIC_COLS = ["mae", "rmse", "r2", "nrmse", "daylight_mae"]

# (display name, metrics csv, name column, name value)
SOURCES = [
    ("zero", "artifacts/baselines/baseline_metrics.csv", "baseline", "zero"),
    ("mean_global", "artifacts/baselines/baseline_metrics.csv", "baseline", "mean_global"),
    ("mean_site", "artifacts/baselines/baseline_metrics.csv", "baseline", "mean_site"),
    ("persistence_prev_day", "artifacts/baselines/baseline_metrics.csv",
     "baseline", "persistence_prev_day"),
    ("xgboost", "artifacts/xgboost/metrics.csv", None, None),
    ("lstm", "artifacts/lstm/metrics.csv", None, None),
    ("gru", "artifacts/gru/metrics.csv", None, None),
    ("transformer", "artifacts/transformer/metrics.csv", None, None),
]


def load_all() -> pd.DataFrame:
    frames = []
    for display, rel, name_col, name_val in SOURCES:
        p = REPO_ROOT / rel
        if not p.exists():
            print(f"skip {display}: {rel} not found")
            continue
        df = pd.read_csv(p)
        df["model"] = display
        if name_col is not None:
            df = df[df[name_col] == name_val]
        if "fit_seconds" in df.columns:
            df["training_seconds"] = df["fit_seconds"]
        # deep-model training time comes from each run's metadata when present
        meta_p = REPO_ROOT / "artifacts" / display / "run_metadata.json"
        if meta_p.exists():
            import json

            secs = json.loads(meta_p.read_text(encoding="utf-8")).get("training_seconds")
            if secs is not None:
                df["training_seconds"] = secs
        frames.append(df)
    if not frames:
        raise SystemExit("no model metrics found under artifacts/")
    return pd.concat(frames, ignore_index=True)


def main() -> int:
    allm = load_all()
    out_dir = REPO_ROOT / "artifacts" / "evaluation"
    out_dir.mkdir(parents=True, exist_ok=True)

    keep = ["model", "split", "scope", "site_id", "n_eval"] + METRIC_COLS
    if "training_seconds" in allm.columns:
        keep.append("training_seconds")

    # ALL-sites comparison table, test first then val, best MAE first
    tab = allm[allm.scope == "ALL"][keep].copy()
    tab["split_order"] = tab.split.map({"test": 0, "val": 1})
    tab = tab.sort_values(["split_order", "mae"]).drop(columns="split_order")
    csv_path = out_dir / "model_comparison.csv"
    tab.to_csv(csv_path, index=False)

    # per-site spread summary per model (test split)
    spread = {}
    site_rows = allm[(allm.scope == "SITE") & (allm.split == "test")]
    for model, sub in site_rows.groupby("model"):
        spread[model] = {
            "sites": int(len(sub)),
            "mae_min": round(float(sub.mae.min()), 3),
            "mae_max": round(float(sub.mae.max()), 3),
            "r2_min": round(float(sub.r2.min()), 3),
            "r2_max": round(float(sub.r2.max()), 3),
            "negative_r2_sites": int((sub.r2 < 0).sum()),
        }

    payload = {
        "generated_from": [rel for _, rel, _, _ in SOURCES
                           if (REPO_ROOT / rel).exists()],
        "all_sites": tab.to_dict(orient="records"),
        "per_site_spread_test": spread,
    }
    json_path = out_dir / "model_comparison.json"
    json_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    lines = ["# Evaluation report (PRD §26)", "",
             f"_Auto-generated by `scripts/compare_models.py`; ALL-scope rows "
             f"only in the table. Same split + nRMSE denominators throughout "
             f"(D-011)._ ", ""]
    for split in ("test", "val"):
        s = tab[tab.split == split].sort_values("mae")
        lines += [f"## {split} split — ALL sites (ranked by MAE)", "",
                  "| model | MAE | RMSE | R² | nRMSE | Daylight MAE | train s |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for r in s.itertuples():
            ts = f"{r.training_seconds:.1f}" if pd.notna(getattr(r, "training_seconds", None)) else ""
            lines.append(f"| {r.model} | {r.mae:.3f} | {r.rmse:.3f} | {r.r2:.3f} "
                         f"| {r.nrmse:.3f} | {getattr(r, 'daylight_mae', float('nan')):.3f} "
                         f"| {ts} |")
        lines.append("")
    lines += ["## Per-site spread (test, 42 sites)", "",
              "| model | MAE min | MAE max | R² min | R² max | neg-R² sites |",
              "|---|---:|---:|---:|---:|---:|"]
    for m, v in spread.items():
        lines.append(f"| {m} | {v['mae_min']} | {v['mae_max']} | {v['r2_min']} "
                     f"| {v['r2_max']} | {v['negative_r2_sites']} |")
    md_path = out_dir / "evaluation_report.md"
    md_path.write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote {csv_path.name}, {json_path.name}, {md_path.name} "
          f"({len(tab)} ALL rows from {allm.model.nunique()} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
