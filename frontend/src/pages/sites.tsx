import { useMemo, useState } from 'react'
import {
  Bar,
  BarChart,
  CartesianGrid,
  ResponsiveContainer,
  Tooltip as RTooltip,
  XAxis,
  YAxis,
} from 'recharts'
import { ArrowDown, ArrowUp, TriangleAlert } from 'lucide-react'

import { Badge } from '@/components/ui/badge'
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table'
import { VizCard, axisTick, gridProps } from '@/components/viz'
import { fmtDate, fmtNum } from '@/lib/format'
import type { SiteSummary } from '@/lib/types'
import siteSummary from '@/data/site_summary.json'

type Col = {
  key: keyof SiteSummary | 'coords'
  label: string
  align?: 'right'
  num?: number
  render?: (s: SiteSummary) => React.ReactNode
  sortVal: (s: SiteSummary) => number | string
}

const bundle = siteSummary as SiteSummary[]

/** Sites (PRD §38): all sites with performance and data availability from
 * the bundled snapshot (scripts/export_frontend_data.py). */
export default function Sites() {
  const [sortKey, setSortKey] = useState<string>('site_id')
  const [dir, setDir] = useState<1 | -1>(1)

  const cols: Col[] = [
    { key: 'site_id', label: 'Site', sortVal: (s) => s.site_id,
      render: (s) => <span className="font-mono">{s.site_id}</span> },
    { key: 'campus_id', label: 'Campus', sortVal: (s) => s.campus_id,
      render: (s) => <span className="font-mono">{s.campus_id}</span> },
    { key: 'coords', label: 'Location', sortVal: (s) => s.latitude ?? 0,
      render: (s) =>
        s.latitude !== null ? (
          <span className="font-mono text-xs text-muted-foreground">
            {s.latitude.toFixed(3)}, {s.longitude!.toFixed(3)}
          </span>
        ) : '—' },
    { key: 'first_ts', label: 'Data span', sortVal: (s) => s.first_ts,
      render: (s) => (
        <span className="text-xs text-muted-foreground">
          {fmtDate(s.first_ts)} → {fmtDate(s.last_ts)}
        </span>
      ) },
    { key: 'mean_daylight_kwh', label: 'Mean daylight kWh', align: 'right',
      num: 2, sortVal: (s) => s.mean_daylight_kwh ?? -1,
      render: (s) => fmtNum(s.mean_daylight_kwh) },
    { key: 'max_daylight_kwh', label: 'Peak kWh', align: 'right',
      num: 1, sortVal: (s) => s.max_daylight_kwh ?? -1,
      render: (s) => fmtNum(s.max_daylight_kwh, 1) },
    { key: 'row_availability_pct', label: 'Row availability', align: 'right',
      num: 1, sortVal: (s) => s.row_availability_pct,
      render: (s) => <Availability pct={s.row_availability_pct} /> },
    { key: 'power_observed_pct', label: 'Power observed', align: 'right',
      num: 1, sortVal: (s) => s.power_observed_pct,
      render: (s) => (
        <span title="Share of slots reporting a value (night reports NaN by design)">
          {fmtNum(s.power_observed_pct, 1)}%
        </span>
      ) },
  ]

  const sorted = useMemo(() => {
    const col = cols.find((c) => c.key === sortKey)!
    return [...bundle].sort((a, b) => {
      const va = col.sortVal(a)
      const vb = col.sortVal(b)
      return (va < vb ? -1 : va > vb ? 1 : 0) * dir
    })
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sortKey, dir])

  function clickCol(key: string) {
    if (sortKey === key) setDir((d) => (d === 1 ? -1 : 1))
    else {
      setSortKey(key)
      setDir(1)
    }
  }

  return (
    <div className="space-y-4">
      <p className="text-sm text-muted-foreground">
        {bundle.length} sites across{' '}
        {new Set(bundle.map((s) => s.campus_id)).size} campuses. Aggregates
        computed over each site's full processed history — snapshot regenerated by{' '}
        <code className="font-mono text-xs">scripts/export_frontend_data.py</code>.
      </p>

      <VizCard
        title="Mean daylight energy per site"
        description="Average kWh generated per daylight day over each site's full history. Capacity differences dominate — compare within a campus, not across."
        table={
          <div className="max-h-80 overflow-auto">
            <table className="w-full text-xs">
              <thead className="sticky top-0 bg-card text-left text-muted-foreground">
                <tr>
                  <th className="px-2 py-1 font-medium">Site</th>
                  <th className="px-2 py-1 text-right font-medium">Mean kWh</th>
                </tr>
              </thead>
              <tbody>
                {[...bundle]
                  .sort((a, b) => (b.mean_daylight_kwh ?? -1) - (a.mean_daylight_kwh ?? -1))
                  .map((s) => (
                    <tr key={s.site_id} className="border-t">
                      <td className="px-2 py-1 font-mono">site {s.site_id}</td>
                      <td className="px-2 py-1 text-right font-mono tabular-nums">
                        {fmtNum(s.mean_daylight_kwh, 1)}
                      </td>
                    </tr>
                  ))}
              </tbody>
            </table>
          </div>
        }
      >
        <figure className="h-80">
          <ResponsiveContainer width="100%" height="100%">
            <BarChart
              data={[...bundle].sort((a, b) => (b.mean_daylight_kwh ?? -1) - (a.mean_daylight_kwh ?? -1))}
              margin={{ top: 8, right: 8, left: 0, bottom: 0 }}
            >
              <CartesianGrid {...gridProps} />
              <XAxis dataKey="site_id" tick={{ ...axisTick }} tickLine={false}
                     axisLine={{ stroke: 'var(--viz-axis)' }} interval={0} />
              <YAxis width={44} tick={{ ...axisTick }} tickLine={false} axisLine={false}
                     tickFormatter={(v: number) => v.toFixed(0)} />
              <RTooltip
                content={({ active, payload, label }) => {
                  if (!active || !payload?.length) return null
                  const s = bundle.find((x) => x.site_id === Number(label))
                  return (
                    <div className="rounded-lg border bg-popover px-3 py-2 text-xs shadow-md">
                      <div className="mb-1 font-mono text-muted-foreground">site {label}</div>
                      <div className="flex items-center gap-2 leading-5">
                        <span className="inline-block size-2 rounded-full" style={{ background: 'var(--chart-1)' }} />
                        <span className="text-muted-foreground">mean daylight</span>
                        <span className="ml-auto pl-4 font-mono tabular-nums">
                          {fmtNum(payload[0].value as number, 1)} kWh/day
                        </span>
                      </div>
                      {s && (
                        <div className="mt-1 font-mono text-[10px] text-muted-foreground">
                          peak {fmtNum(s.max_daylight_kwh, 1)} kWh · campus {s.campus_id}
                        </div>
                      )}
                    </div>
                  )
                }}
              />
              <Bar dataKey={(s: SiteSummary) => s.mean_daylight_kwh ?? 0}
                   name="mean daylight kWh" fill="var(--chart-1)" radius={[3, 3, 0, 0]}
                   isAnimationActive={false} />
            </BarChart>
          </ResponsiveContainer>
        </figure>
      </VizCard>

      <div className="overflow-x-auto rounded-lg border bg-card">
        <Table>
          <TableHeader>
            <TableRow>
              {cols.map((c) => (
                <TableHead
                  key={c.key}
                  aria-sort={
                    sortKey === c.key
                      ? dir === 1 ? 'ascending' : 'descending'
                      : 'none'
                  }
                >
                  <button
                    className="inline-flex items-center gap-1 hover:text-foreground"
                    onClick={() => clickCol(c.key)}
                  >
                    {c.label}
                    {sortKey === c.key &&
                      (dir === 1 ? <ArrowUp className="size-3" /> : <ArrowDown className="size-3" />)}
                  </button>
                </TableHead>
              ))}
            </TableRow>
          </TableHeader>
          <TableBody>
            {sorted.map((s) => (
              <TableRow key={s.site_id}>
                {cols.map((c) => (
                  <TableCell key={c.key} className={c.align === 'right' ? 'text-right tabular-nums' : ''}>
                    {c.render ? c.render(s) : String(s[c.key as keyof SiteSummary] ?? '—')}
                  </TableCell>
                ))}
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </div>
    </div>
  )
}

function Availability({ pct }: { pct: number }) {
  if (pct >= 95)
    return <span className="tabular-nums">{fmtNum(pct, 1)}%</span>
  return (
    <Badge variant="outline" className="gap-1 font-mono text-status-serious">
      <TriangleAlert aria-hidden /> {fmtNum(pct, 1)}%
    </Badge>
  )
}
